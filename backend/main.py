"""TrustCare XAI - mock backend.

FastAPI service that emulates the final Clinical Decision Support System.
All predictions are generated by a rule-based mock engine; there is no
machine-learning model. To integrate a real model later, replace
`services.analysis.analyze_patient` - the API contract stays the same.

Run:  uvicorn main:app --reload --port 8000
"""

from __future__ import annotations

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from routes import analyze, dashboard, patients, reports

app = FastAPI(
    title="TrustCare XAI API",
    description="Explainable AI for Medication Adherence Risk Assessment (mock backend)",
    version="0.1.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # prototype: allow the Vite dev server on any port
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(dashboard.router)
app.include_router(patients.router)
app.include_router(analyze.router)
app.include_router(reports.router)


@app.get("/")
def root() -> dict:
    return {
        "name": "TrustCare XAI API",
        "status": "ok",
        "note": "Mock backend - predictions are simulated, no ML model in use.",
        "docs": "/docs",
    }
